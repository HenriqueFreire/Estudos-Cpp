#include <iostream>

/*
  Este é um comentário de bloco
  Ele pode se estender por múltiplas linhas.
*/

// Tudo entre o /* e o */ é ignorado pelo compilador
// A função main abaixo é o ponto de partida
int main() {
  // Este é o comentário de uma única linha
  std::cout << "Comentários são importantes!\n";

  return 0;
}

